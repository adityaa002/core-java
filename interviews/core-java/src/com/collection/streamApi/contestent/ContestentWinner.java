package com.collection.streamApi.contestent;

public class ContestentWinner {

	String name;
	String phone;

	public ContestentWinner(String name, String phone) {

		this.name = name;
		this.phone = phone;
	}

	public String getName() {
		return name;
	}

	public String getPhone() {
		return phone;
	}

}
